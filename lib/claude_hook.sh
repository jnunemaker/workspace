#!/bin/sh
# workspace claude-hook — Claude Code session hooks for linked Git worktrees.
#
# Claude Code has no native setup or cleanup script, so `workspace init` wires
# these into .claude/settings.json. Measured desktop app behavior they rely on:
#
#   - Hooks run from the original checkout; the session's worktree is only
#     available as "cwd" in the JSON on stdin.
#   - A new session fires SessionStart "startup"; unarchiving fires "resume".
#   - Archiving fires SessionEnd "other" after releasing the worktree's branch
#     (detached HEAD). The worktree directory is never deleted.
#
# session-start bootstraps the worktree once and remembers which branch the
# session owns. session-end archives only when that remembered branch has been
# released, which separates archive from quitting the app or a stopped
# process, and never touches worktrees that started detached (Codex).

set -e

WORKSPACE_LIB="$(cd "$(dirname "$0")" && pwd)"

if [ "${1:-}" = "--help" ] || [ "${1:-}" = "-h" ] || [ -z "${1:-}" ]; then
  cat <<'EOF'
Usage: workspace claude-hook <session-start|session-end>

Reads Claude Code hook JSON on stdin. Generated by workspace init in
.claude/settings.json; not normally run by hand.

  session-start  Bootstrap the session's linked Git worktree once
  session-end    Archive the worktree in the background after Claude Code
                 archives the session (its branch was released)
EOF
  [ -n "${1:-}" ] && exit 0
  exit 1
fi

_claude_event="$1"
_claude_input=$(cat)

# Paths with JSON escapes are not supported; fail closed rather than guess.
_claude_cwd=$(printf '%s' "$_claude_input" | tr -d '\n' \
  | sed -n 's/.*"cwd"[[:space:]]*:[[:space:]]*"\([^"\\]*\)".*/\1/p')
[ -n "$_claude_cwd" ] && [ -d "$_claude_cwd" ] || exit 0
cd "$_claude_cwd"

# Only linked Git worktrees: the original checkout keeps its own lifecycle.
_claude_git_dir=$(git rev-parse --absolute-git-dir 2>/dev/null) || exit 0
_claude_common_dir=$(cd "$(git rev-parse --git-common-dir)" 2>/dev/null && pwd -P) || exit 0
[ "$(cd "$_claude_git_dir" && pwd -P)" != "$_claude_common_dir" ] || exit 0
[ -x bin/workspace ] || exit 0

_claude_branch_marker="$_claude_git_dir/workspace-claude-branch"
_claude_archived_marker="$_claude_git_dir/workspace-claude-archived"
_claude_log="$_claude_git_dir/workspace-claude.log"

case "$_claude_event" in
  session-start)
    if _claude_branch=$(git symbolic-ref -q --short HEAD); then
      printf '%s\n' "$_claude_branch" > "$_claude_branch_marker"
    fi
    # Bootstrap output belongs in the hook log, not Claude's context.
    # An unarchived worktree still has its .workspace marker but no databases,
    # so --once would skip it. Keep the archived marker until setup succeeds.
    if [ -f "$_claude_archived_marker" ]; then
      sh "$WORKSPACE_LIB/bootstrap.sh" >&2
      rm -f "$_claude_archived_marker"
      exit 0
    fi
    exec sh "$WORKSPACE_LIB/bootstrap.sh" --once >&2
    ;;
  session-end)
    [ -f "$_claude_branch_marker" ] || exit 0
    git symbolic-ref -q HEAD >/dev/null && exit 0
    # A rebase or bisect detaches HEAD on purpose; that is not an archive.
    for _claude_in_progress in rebase-merge rebase-apply BISECT_LOG; do
      [ ! -e "$_claude_git_dir/$_claude_in_progress" ] || exit 0
    done
    rm -f "$_claude_branch_marker"
    # SessionEnd hooks get at most 60 seconds; archive may need longer.
    nohup sh -c '
      printf "=== archive %s\n" "$(date)"
      if sh "$1/archive.sh"; then
        : > "$2"
      fi
    ' sh "$WORKSPACE_LIB" "$_claude_archived_marker" >> "$_claude_log" 2>&1 &
    exit 0
    ;;
  *)
    echo "workspace claude-hook: unknown event '$_claude_event'" >&2
    exit 1
    ;;
esac
